import { chromium } from "playwright";
import assert from "node:assert/strict";
import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { resolve, extname, sep } from "node:path";
const root=resolve("app/src/main/assets");
const types={".html":"text/html; charset=utf-8",".json":"application/json",".jpg":"image/jpeg",".mp4":"video/mp4"};
const server=createServer(async(req,res)=>{try{const url=new URL(req.url,"http://localhost");const path=resolve(root,"."+decodeURIComponent(url.pathname));if(!path.startsWith(root+sep))throw Error("invalid path");const bytes=await readFile(path);res.writeHead(200,{"Content-Type":types[extname(path)]||"application/octet-stream"});res.end(bytes)}catch{res.writeHead(404);res.end()}});
await new Promise(r=>server.listen(0,"127.0.0.1",r));
let browser;
try{
 browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
 for(const width of [320,390,768]){
  const ctx=await browser.newContext({viewport:{width,height:844},isMobile:width<500,hasTouch:width<500,deviceScaleFactor:1});
  const page=await ctx.newPage(),errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  const url="http://127.0.0.1:"+server.address().port+"/index.html";
  const noOverflow=async()=>assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),"horizontal overflow "+width+" "+page.url());
  await page.goto(url+"#/home");
  await page.locator("#search").fill("инсульт");
  assert.ok(page.url().endsWith("#/home"),"search must remain on home");
  assert.ok(await page.locator("#home-results").isVisible());
  assert.ok(await page.locator('#home-results a[href="#/topic/stroke"]').count());
  await noOverflow();
  await page.locator("#search").fill("");
  assert.ok(await page.locator("#home-browse").isVisible());
  await page.locator('nav a[href="#/sos"]').click();
  assert.ok(await page.locator(".emergency-tile").count()>=8);
  await noOverflow();
  await page.locator('.emergency-tile[href="#/topic/cpr"]').click();
  assert.ok(await page.locator(".step-list .step").count()>0);
  assert.ok(await page.locator('a[href="tel:112"]').first().isVisible());
  await noOverflow();
  await page.screenshot({path:"puls-sos-"+width+".png"});
  await page.locator('nav a[href="#/kits"]').click();
  assert.equal(await page.locator(".kit-v84").count(),3);
  assert.equal(await page.locator('.kit-v84 input[data-check]').count(),13);
  await page.locator('[data-check="home:0"]').check();
  await page.reload();
  assert.ok(await page.locator('[data-check="home:0"]').isChecked());
  await page.locator('[data-kit="travel"]').click();
  assert.equal(await page.locator('.kit-v84 input[data-check]').count(),14);
  await page.locator('[data-kit="outdoor"]').click();
  assert.equal(await page.locator('.kit-v84 input[data-check]').count(),15);
  await noOverflow();
  await page.screenshot({path:"puls-kit-"+width+".png"});
  await page.locator('a[href="#/kits/medicines"]').click();
  await page.locator("#medicine-search").fill("регидрон");
  assert.equal(await page.locator(".medicine-row").count(),1);
  await page.locator(".med-info summary").click();
  assert.ok(await page.locator(".med-info a.link").isVisible());
  await page.locator("#medicine-search").fill("zznoresults");
  assert.equal(await page.locator(".medicine-row").count(),0);
  await page.locator("#medicine-search").fill("");
  assert.equal(await page.locator(".medicine-row").count(),27);
  await noOverflow();
  await page.screenshot({path:"puls-medicines-"+width+".png"});
  await page.locator('nav a[href="#/catalog"]').click();
  const category=await page.locator("[data-cat]").evaluateAll(nodes=>nodes.map(n=>n.dataset.cat).find(x=>x!=="all"));assert.ok(category);
  await page.locator('[data-cat="'+category+'"]').click();
  assert.ok(page.url().endsWith("#/catalog/"+category));
  await page.locator('[data-cat="all"]').click();
  assert.ok(page.url().endsWith("#/catalog/all"));
  await page.locator("#langbtn").click();
  assert.equal(await page.locator("html").getAttribute("lang"),"en");
  await noOverflow();
  assert.deepEqual(errors,[],"uncaught JS errors at "+width);
  await ctx.close();
  console.log("PASS browser viewport",width);
 }
}finally{await browser?.close();server.close()}
